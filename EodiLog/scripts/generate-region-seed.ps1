param([switch]$Check)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
& "$PSScriptRoot/verify-region-snapshot.ps1"
$manifest = Get-Content -Raw -Encoding utf8 "$root/docs/data/regions/seed-manifest.json" | ConvertFrom-Json
if ($manifest.nodes.Count -ne 245 -or $manifest.aliases.Count -ne 39) { throw 'Unexpected snapshot size' }
$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('-- Generated by scripts/generate-region-seed.ps1 from docs/data/regions/seed-manifest.json. Do not edit.')
$lines.Add('CREATE TABLE region_code_aliases (code varchar(10) PRIMARY KEY, region_id uuid NOT NULL REFERENCES regions(id));')
$lines.Add('CREATE TABLE region_code_targets (code varchar(10) PRIMARY KEY, region_id uuid NOT NULL REFERENCES regions(id));')
foreach ($node in $manifest.nodes | Sort-Object { if ($null -eq $_.parentCode) { 0 } else { 1 } }, code) {
    $name = $node.name.Trim().Replace("'", "''")
    $parent = if ($null -eq $node.parentCode) { 'NULL' } else { "(SELECT id FROM regions WHERE code='$($node.parentCode)')" }
    $lines.Add("INSERT INTO regions(id,code,name,parent_id) VALUES ('$($node.id)','$($node.code)','$name',$parent) ON CONFLICT(code) DO UPDATE SET parent_id=EXCLUDED.parent_id;")
}
foreach ($node in $manifest.nodes | Where-Object { $null -ne $_.parentCode -or $_.code -eq '3611000000' } | Sort-Object code) {
    $lines.Add("INSERT INTO region_code_targets(code,region_id) SELECT '$($node.code)',id FROM regions WHERE code='$($node.code)' ON CONFLICT(code) DO NOTHING;")
}
foreach ($alias in $manifest.aliases | Sort-Object sourceSigunguCode) {
    $lines.Add("INSERT INTO region_code_aliases(code,region_id) SELECT '$($alias.sourceSigunguCode)',id FROM regions WHERE code='$($alias.targetCode)' ON CONFLICT(code) DO NOTHING;")
}
$sql = ($lines -join "`n") + "`n"
$target = "$root/src/main/resources/db/migration/V202611021500__seed_regions.sql"
if ($Check) { if ([IO.File]::ReadAllText($target).Replace("`r`n", "`n") -cne $sql) { throw 'Generated SQL differs' }; Write-Output 'Region seed matches manifest' }
else { [IO.File]::WriteAllText($target,$sql,[Text.UTF8Encoding]::new($false)) }

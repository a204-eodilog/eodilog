package com.eodilog.region;

import static org.assertj.core.api.Assertions.*;

import java.nio.charset.Charset;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.security.MessageDigest;
import java.util.*;
import java.util.zip.ZipFile;
import org.junit.jupiter.api.Test;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;

/** Portable build check: no PowerShell, network, database or generated UUIDs. */
class RegionSeedArtifactTest {
    private static final Path DATA = Path.of("docs/data/regions");
    private record Node(String id,String code,String name,String parentCode) { }

    @Test void officialSnapshotManifestAndCommittedMigrationAgree() throws Exception {
        JsonNode manifest;
        try (var input = Files.newInputStream(DATA.resolve("seed-manifest.json"))) {
            manifest = JsonMapper.builder().build().readTree(input);
        }
        byte[] zipBytes = Files.readAllBytes(DATA.resolve("legal-region-full.zip"));
        String zipHash = sha256(zipBytes);
        assertThat(zipHash).isEqualTo("44a3fe4cacf88ce98e35fb883807d2725b589f427ff4d73ee40b914d1286bacd")
                .isEqualTo(manifest.path("metadata").path("zipSha256").asText());
        byte[] rawBytes;
        try (var zip = new ZipFile(DATA.resolve("legal-region-full.zip").toFile(),Charset.forName("MS949"))) {
            assertThat(zip.size()).isEqualTo(1);
            try (var input = zip.getInputStream(zip.entries().nextElement())) { rawBytes = input.readAllBytes(); }
        }
        assertThat(sha256(rawBytes)).isEqualTo("962fd4cdfb6ccf2887b745eb97db55f71112b9f9a32c1f8fbd7692fb069b1df0")
                .isEqualTo(manifest.path("metadata").path("rawTxtSha256").asText());
        var active = new TreeMap<String,String>();
        String[] lines = new String(rawBytes,Charset.forName("MS949")).split("\\R");
        for (int i=1;i<lines.length;i++) {
            String[] fields=lines[i].split("\t",-1);
            if (fields.length==3 && fields[2].strip().equals("존재")) active.put(fields[0],fields[1].strip());
        }
        assertThat(active).hasSize(20560);
        var official = new TreeMap<String,String>();
        var byName = new HashMap<String,String>();
        active.forEach((code,name) -> {
            if (code.endsWith("00000") && name.split("\\s+").length<=2) { official.put(code,name); byName.put(name,code); }
        });
        assertThat(official).hasSize(245);
        var nodes = new ArrayList<Node>();
        var ids = new HashSet<UUID>();
        for (int i=0;i<manifest.path("nodes").size();i++) {
            var node=manifest.path("nodes").get(i);
            String parent=node.path("parentCode").isNull() ? null : node.path("parentCode").asText();
            var value=new Node(node.path("id").asText(),node.path("code").asText(),node.path("name").asText(),parent);
            UUID id=UUID.fromString(value.id());
            assertThat(id.version()).isEqualTo(7); assertThat(ids.add(id)).isTrue();
            assertThat(value.name()).isEqualTo(official.get(value.code())).isEqualTo(value.name().strip());
            String[] parts=value.name().split("\\s+");
            assertThat(parent).isEqualTo(parts.length==1 ? null : byName.get(parts[0]));
            nodes.add(value);
        }
        assertThat(nodes).hasSize(245);
        assertThat(nodes).extracting(Node::code).containsExactlyInAnyOrderElementsOf(official.keySet());
        assertThat(nodes.stream().filter(n -> n.parentCode()==null).count()).isEqualTo(16);
        var officialAliases = new TreeMap<String,String>();
        active.forEach((code,name) -> {
            String[] parts=name.split("\\s+");
            if (code.endsWith("00000") && parts.length==3) {
                String target=byName.get(parts[0]+" "+parts[1]);
                assertThat(target).isNotNull(); officialAliases.put(code,target);
            }
        });
        var aliases = new TreeMap<String,String>();
        for (int i=0;i<manifest.path("aliases").size();i++) {
            var alias=manifest.path("aliases").get(i);
            assertThat(aliases.put(alias.path("sourceSigunguCode").asText(),alias.path("targetCode").asText())).isNull();
        }
        assertThat(aliases).hasSize(39).isEqualTo(officialAliases);
        var sql=new StringBuilder("-- Generated by scripts/generate-region-seed.ps1 from docs/data/regions/seed-manifest.json. Do not edit.\n");
        sql.append("CREATE TABLE region_code_aliases (code varchar(10) PRIMARY KEY, region_id uuid NOT NULL REFERENCES regions(id));\n");
        sql.append("CREATE TABLE region_code_targets (code varchar(10) PRIMARY KEY, region_id uuid NOT NULL REFERENCES regions(id));\n");
        nodes.sort(Comparator.comparing((Node n) -> n.parentCode()!=null).thenComparing(Node::code));
        for (var n:nodes) {
            String parent=n.parentCode()==null ? "NULL" : "(SELECT id FROM regions WHERE code='"+n.parentCode()+"')";
            sql.append("INSERT INTO regions(id,code,name,parent_id) VALUES ('").append(n.id()).append("','").append(n.code()).append("','")
                    .append(n.name().replace("'","''")).append("',").append(parent).append(") ON CONFLICT(code) DO UPDATE SET parent_id=EXCLUDED.parent_id;\n");
        }
        var targets=nodes.stream().filter(n -> n.parentCode()!=null || n.code().equals("3611000000")).sorted(Comparator.comparing(Node::code)).toList();
        assertThat(targets).hasSize(230);
        for (var n:targets) sql.append("INSERT INTO region_code_targets(code,region_id) SELECT '").append(n.code()).append("',id FROM regions WHERE code='").append(n.code()).append("' ON CONFLICT(code) DO NOTHING;\n");
        aliases.forEach((code,target) -> sql.append("INSERT INTO region_code_aliases(code,region_id) SELECT '").append(code).append("',id FROM regions WHERE code='").append(target).append("' ON CONFLICT(code) DO NOTHING;\n"));
        String committed=Files.readString(Path.of("src/main/resources/db/migration/V202611021500__seed_regions.sql"),StandardCharsets.UTF_8);
        assertThat(committed.replace("\r\n","\n")).isEqualTo(sql.toString());
    }
    private static String sha256(byte[] bytes) throws Exception { return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(bytes)); }
}

package com.eodilog.job;

public enum JobKind {
    PREFERENCE_INFERENCE, PLACE_EXTRACTION, TRIP_RECOMMENDATION, ITINERARY_PROPOSAL, WEATHER_ALTERNATIVES,
    CHECKLIST_SUGGESTIONS, PHOTO_CLASSIFICATION, VISIT_DETECTION, ROUTE_RECALCULATION,
    LEAVE_CLEANUP, PHOTO_DELETE, TRIP_DELETE, ACCOUNT_DELETE;

    public boolean cleanup() {
        return this == LEAVE_CLEANUP || this == PHOTO_DELETE || this == TRIP_DELETE || this == ACCOUNT_DELETE;
    }
}
